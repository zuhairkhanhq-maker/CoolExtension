import { readFile,cp,writeFile,mkdir } from 'node:fs/promises';
import { resolve,dirname } from 'node:path';
import {pathToFileURL,fileURLToPath} from 'node:url';
const [apiOrigin,publicKeyPath,outputPath]=process.argv.slice(2);
if(!apiOrigin||!publicKeyPath)throw Error('Usage: node scripts/configure-extension.js https://billing.yourdomain.com /absolute/path/public-jwk.json');
const url=new URL(apiOrigin);if(url.protocol!=='https:'||url.origin!==apiOrigin)throw Error('Use an HTTPS origin without a trailing slash.');
const key=JSON.parse(await readFile(resolve(publicKeyPath),'utf8'));
if(key.d||key.kty!=='EC'||key.crv!=='P-256'||!key.x||!key.y||!key.kid)throw Error('Provide only a public P-256 JWK with kid. Never pass the private key.');
const source=new URL('../../Bypass-Extension/',import.meta.url),target=outputPath?pathToFileURL(resolve(outputPath)+'/'):new URL('../../build/Bypass-Extension/',import.meta.url);
await mkdir(dirname(fileURLToPath(target)),{recursive:true});
await mkdir(target);await cp(source,target,{recursive:true,filter:path=>!path.includes('/tests')});
await writeFile(new URL('core/billing-config.js',target),`'use strict';\nglobalThis.BypassBillingConfig=Object.freeze(${JSON.stringify({enabled:true,apiOrigin,publicKeys:[key]})});\n`);
const manifest=JSON.parse(await readFile(new URL('manifest.json',target),'utf8'));
manifest.version='0.8.0';manifest.version_name='0.8.0 Billing Integration Candidate';
for(const script of manifest.content_scripts)script.exclude_matches=[...new Set([...(script.exclude_matches||[]),apiOrigin+'/*','https://*.paddle.com/*'])];
await writeFile(new URL('manifest.json',target),JSON.stringify(manifest,null,2)+'\n');
console.log(`Configured extension: ${fileURLToPath(target)}. Server secrets were not copied.`);
